create or replace view V_ORDERCOMPONENT_GROUPED(
	JOBNUMBER,
	USERDEFINED6,
	ENTRYDATE,
	DUEDATE,
	DELIVERYDATE,
	PROOFDUEDATE,
	PROOFDELIVERYDATE,
	CREATEDATIM,
	UPDATEDATIM,
	COMPONENTNUMBER,
	COMPONENTTYPE,
	COMPONENT_TYPE,
	FINGOODCODE,
	USEQUANTITYTABLE,
	DISCOUNT,
	MANUALPRESSOUTS,
	ESTIMATENUMBER,
	CHARGEZERO,
	DONTCALCULATE,
	COMPONENTPLANNED,
	MANUALPRICEMETHOD,
	MANUALPRICEOVERRIDE,
	USERDEFINED2,
	USERDEFINED4,
	ID,
	HEADERID,
	TAXJURISDICTION,
	SUM_QUANTITYORDERED,
	SUM_PRODUCTIONMARKUP,
	SUM_MATERIALMARKUP,
	SUM_STOCKMARKUP,
	SUM_TOTALSELLPRICE,
	SUM_DISCOUNTDOLLARS,
	ROW_COUNT
) as
SELECT
    JOBNUMBER,
    USERDEFINED6,
    ENTRYDATE,
    DUEDATE,
    DELIVERYDATE,
    PROOFDUEDATE,
    PROOFDELIVERYDATE,
    CREATEDATIM,
    UPDATEDATIM,
    COMPONENTNUMBER,
    COMPONENTTYPE,
    COMPONENT_TYPE,
    FINGOODCODE,
    USEQUANTITYTABLE,
    DISCOUNT,
    MANUALPRESSOUTS,
    ESTIMATENUMBER,
    CHARGEZERO,
    DONTCALCULATE,
    COMPONENTPLANNED,
    MANUALPRICEMETHOD,
    MANUALPRICEOVERRIDE,
    USERDEFINED2,
    USERDEFINED4,
    ID,
    HEADERID,
    TAXJURISDICTION,

    SUM(QUANTITYORDERED) AS SUM_QUANTITYORDERED,
    SUM(PRODUCTIONMARKUP) AS SUM_PRODUCTIONMARKUP,
    SUM(MATERIALMARKUP) AS SUM_MATERIALMARKUP,
    SUM(STOCKMARKUP) AS SUM_STOCKMARKUP,
    SUM(TOTALSELLPRICE) AS SUM_TOTALSELLPRICE,
    SUM(DISCOUNTDOLLARS) AS SUM_DISCOUNTDOLLARS,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERCOMPONENT
GROUP BY
    JOBNUMBER,
    USERDEFINED6,
    ENTRYDATE,
    DUEDATE,
    DELIVERYDATE,
    PROOFDUEDATE,
    PROOFDELIVERYDATE,
    CREATEDATIM,
    UPDATEDATIM,
    COMPONENTNUMBER,
    COMPONENTTYPE,
    COMPONENT_TYPE,
    FINGOODCODE,
    USEQUANTITYTABLE,
    DISCOUNT,
    MANUALPRESSOUTS,
    ESTIMATENUMBER,
    CHARGEZERO,
    DONTCALCULATE,
    COMPONENTPLANNED,
    MANUALPRICEMETHOD,
    MANUALPRICEOVERRIDE,
    USERDEFINED2,
    USERDEFINED4,
    ID,
    HEADERID,
    TAXJURISDICTION;;
