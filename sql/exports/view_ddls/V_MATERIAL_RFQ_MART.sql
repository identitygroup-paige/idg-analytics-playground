create or replace view V_MATERIAL_RFQ_MART(
	JOBNUMBER,
	COMPONENTNUMBER,
	MATERIALCODE,
	REQUISITION_CODE,
	GLACCOUNT,
	VENDORPRODUCTID,
	COSTINGMETHOD,
	LINEITEMTYPE,
	VENDORID,
	LOCATIONCODE,
	MULTILOCATION,
	PLANTID,
	DUEDATE,
	MANUFACTURERITEMNUMBER,
	REQUISITION_QUANTITY,
	REQUISITION_UNITCOST,
	REQUISITION_EXTENDEDCOST,
	REQUISITION_FIXEDQUANTITY,
	REQUISITION_FIXEDUNITCOST,
	REQUISITION_QUANTITYTOORDER,
	REQUISITION_ROW_COUNT,
	RFQNUMBER,
	RFQ_ESTIMATENUMBER,
	RFQ_ORDERNUMBER,
	RFQ_PRICINGDONE,
	RFQ_CUSTACCOUNT,
	RFQ_CUSTNAME,
	RFQ_CUSTSTATE,
	RFQ_CUSTZIP,
	RFQDUEDATE,
	RFQ_ARJOBCLOSEOUT,
	RFQ_COMPONENTTYPE,
	RFQ_COMPONENT_TOTAL_QUANTITY,
	RFQ_COMPONENT_TOTAL_PRICE,
	RFQCOMPONENTVALUEID,
	RFQ_COMPONENT_VALUE,
	RFQHEADER_ROW_COUNT,
	RFQCOMPONENT_ROW_COUNT,
	RFQCOMPONENTVALUE_ROW_COUNT
) as
SELECT
    r.JOBNUMBER,
    r.COMPONENTNUMBER,
    r.MATERIALCODE,

    r.CODE AS REQUISITION_CODE,
    r.GLACCOUNT,
    r.VENDORPRODUCTID,
    r.COSTINGMETHOD,
    r.LINEITEMTYPE,
    r.VENDORID,
    r.LOCATIONCODE,
    r.MULTILOCATION,
    r.PLANTID,
    r.DUEDATE,
    r.MANUFACTURERITEMNUMBER,

    r.SUM_QUANTITY AS REQUISITION_QUANTITY,
    r.SUM_UNITCOST AS REQUISITION_UNITCOST,
    r.SUM_EXTENDEDCOST AS REQUISITION_EXTENDEDCOST,
    r.SUM_FIXEDQUANTITY AS REQUISITION_FIXEDQUANTITY,
    r.SUM_FIXEDUNITCOST AS REQUISITION_FIXEDUNITCOST,
    r.SUM_QUANTITYTOORDER AS REQUISITION_QUANTITYTOORDER,
    r.ROW_COUNT AS REQUISITION_ROW_COUNT,

    rfq.RFQNUMBER,
    rfq.RFQ_ESTIMATENUMBER,
    rfq.RFQ_ORDERNUMBER,
    rfq.RFQ_PRICINGDONE,
    rfq.RFQ_CUSTACCOUNT,
    rfq.RFQ_CUSTNAME,
    rfq.RFQ_CUSTSTATE,
    rfq.RFQ_CUSTZIP,
    rfq.RFQDUEDATE,
    rfq.RFQ_ARJOBCLOSEOUT,
    rfq.RFQ_COMPONENTTYPE,
    rfq.RFQ_COMPONENT_TOTAL_QUANTITY,
    rfq.RFQ_COMPONENT_TOTAL_PRICE,
    rfq.RFQCOMPONENTVALUEID,
    rfq.RFQ_COMPONENT_VALUE,
    rfq.RFQHEADER_ROW_COUNT,
    rfq.RFQCOMPONENT_ROW_COUNT,
    rfq.RFQCOMPONENTVALUE_ROW_COUNT

FROM DATA_VALIDATION.MART_REVENUE.V_REQUISITION_GROUPED r

LEFT JOIN DATA_VALIDATION.MART_REVENUE.V_REQUISITION_RFQ_ENRICHED rfq
    ON r.JOBNUMBER = rfq.JOBNUMBER
   AND r.COMPONENTNUMBER = rfq.COMPONENTNUMBER
   AND r.MATERIALCODE = rfq.MATERIALCODE;;
