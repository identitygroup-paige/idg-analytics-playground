create or replace view V_ORDERHEADER_ANALYTICS(
	JOBNUMBER,
	ESTIMATENUMBER,
	FORMNUMBER,
	CUSTACCOUNT,
	CUSTNAME,
	CUSTSTATE,
	PLANTID,
	ORDERDATE,
	DUEDATE,
	DELIVERYDATE,
	ORDERTYPE,
	PONUMBER,
	PODATE,
	CREATEDATIM,
	UPDATEDATIM,
	JOBSTATUS,
	USERDEFINED1,
	USERDEFINED4,
	USERDEFINED5,
	ESTIMATESTATUS,
	SUM_PREPAYMENT,
	SUM_TOTALCOMPONENTS,
	SUM_TOTALCOMPONENTSQTYCALCULATED,
	SUM_TOTALSELLPRICE,
	SUM_ORDERSELLPRICE,
	SUM_INVOICESELLPRICE,
	SUM_INVOICEDFREIGHTPRICE,
	SUM_CALCULATEDTOTALPRICE,
	SUM_DISCOUNT,
	ROW_COUNT
) as
    SELECT
        JOBNUMBER,
        ESTIMATENUMBER,
        FORMNUMBER,
        CUSTACCOUNT,
        CUSTNAME,
        CUSTSTATE,
        PLANTID,
        ORDERDATE,
        DUEDATE,
        DELIVERYDATE,
        ORDERTYPE,
        PONUMBER,
        PODATE,
        CREATEDATIM,
        UPDATEDATIM,
        JOBSTATUS,
        USERDEFINED1,
        USERDEFINED4,
        USERDEFINED5,
        ESTIMATESTATUS,
        SUM(PREPAYMENT) AS SUM_PREPAYMENT,
        SUM(TOTALCOMPONENTS) AS SUM_TOTALCOMPONENTS,
        SUM(TOTALCOMPONENTSQTYCALCULATED) AS SUM_TOTALCOMPONENTSQTYCALCULATED,
        SUM(TOTALSELLPRICE) AS SUM_TOTALSELLPRICE,
        SUM(ORDERSELLPRICE) AS SUM_ORDERSELLPRICE,
        SUM(INVOICESELLPRICE) AS SUM_INVOICESELLPRICE,
        SUM(INVOICEDFREIGHTPRICE) AS SUM_INVOICEDFREIGHTPRICE,
        SUM(CALCULATEDTOTALPRICE) AS SUM_CALCULATEDTOTALPRICE,
        SUM(DISCOUNT) AS SUM_DISCOUNT,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERHEADER
GROUP BY
JOBNUMBER,
        ESTIMATENUMBER,
        FORMNUMBER,
        CUSTACCOUNT,
        CUSTNAME,
        CUSTSTATE,
        PLANTID,
        ORDERDATE,
        DUEDATE,
        DELIVERYDATE,
        ORDERTYPE,
        PONUMBER,
        PLANTID,
        PODATE,
        CREATEDATIM,
        UPDATEDATIM,
        JOBSTATUS,
        USERDEFINED1,
        USERDEFINED4,
        USERDEFINED5,
        ESTIMATESTATUS;;
