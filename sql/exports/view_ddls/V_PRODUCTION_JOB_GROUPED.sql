create or replace view V_PRODUCTION_JOB_GROUPED(
	CODE,
	JOBNUMBER,
	COMPONENTNUMBER,
	STARTDATE,
	EMPLOYEECODE,
	PROCESSCODE,
	COMPLETIONCODE,
	REASONCODE,
	COSTCODE,
	GANGRUN,
	ENTRYDATE,
	DEPARTMENTCODE,
	CREATEDATIM,
	UPDATEDATIM,
	GANGRUNBYAREA,
	POSTEDTOGL,
	GRJOBNUMBER,
	CREWLEADERPROCESSCODE,
	GANGCOMPONENTNUMBER,
	SUM_PERCENTAGE,
	SUM_JOB_QUANTITY,
	SUM_QUANTITY,
	SUM_ELAPSEDTIME,
	SUM_CONCURRENT,
	SUM_AIRATE,
	SUM_DMRATE,
	SUM_OVERTIMEINCREASE,
	SUM_DOUBLETIMEINCREASE,
	SUM_UNITCOST,
	SUM_AICOST,
	SUM_DMCOST,
	SUM_TOTALCOPIES,
	SUM_GOODCOPIES,
	SUM_ACTUALWASTE,
	SUM_ENDCOUNT,
	SUM_STARTCOUNT,
	SUM_WAGERATE,
	SUM_WAGECOST,
	SUM_OVERTIMEWAGECOST,
	SUM_OVERTIMEWAGERATE,
	SUM_GANGRUNBYQUANTITY,
	SUM_BADQUANTITY,
	SUM_POSTAGECOST,
	SUM_PLANNEDWASTE,
	SUM_WIPRATE,
	SUM_WIPCOST,
	SUM_INLINEOPRATE,
	SUM_INLINEOPCOST,
	ROW_COUNT
) as
SELECT
    P.CODE,
    PJ.JOBNUMBER,
    PJ.COMPONENTNUMBER,

    P.STARTDATE,
    P.EMPLOYEECODE,
    P.PROCESSCODE,
    P.COMPLETIONCODE,
    P.REASONCODE,
    P.COSTCODE,
    P.GANGRUN,
    P.ENTRYDATE,
    P.DEPARTMENTCODE,
    P.CREATEDATIM,
    P.UPDATEDATIM,
    P.GANGRUNBYAREA,
    P.POSTEDTOGL,
    P.GRJOBNUMBER,
    P.CREWLEADERPROCESSCODE,
    P.GANGCOMPONENTNUMBER,

    SUM(PJ.PERCENTAGE) AS SUM_PERCENTAGE,
    SUM(PJ.QUANTITY) AS SUM_JOB_QUANTITY,

    SUM(P.SUM_QUANTITY) AS SUM_QUANTITY,
    SUM(P.SUM_ELAPSEDTIME) AS SUM_ELAPSEDTIME,
    SUM(P.SUM_CONCURRENT) AS SUM_CONCURRENT,
    SUM(P.SUM_AIRATE) AS SUM_AIRATE,
    SUM(P.SUM_DMRATE) AS SUM_DMRATE,
    SUM(P.SUM_OVERTIMEINCREASE) AS SUM_OVERTIMEINCREASE,
    SUM(P.SUM_DOUBLETIMEINCREASE) AS SUM_DOUBLETIMEINCREASE,
    SUM(P.SUM_UNITCOST) AS SUM_UNITCOST,
    SUM(P.SUM_AICOST) AS SUM_AICOST,
    SUM(P.SUM_DMCOST) AS SUM_DMCOST,
    SUM(P.SUM_TOTALCOPIES) AS SUM_TOTALCOPIES,
    SUM(P.SUM_GOODCOPIES) AS SUM_GOODCOPIES,
    SUM(P.SUM_ACTUALWASTE) AS SUM_ACTUALWASTE,
    SUM(P.SUM_ENDCOUNT) AS SUM_ENDCOUNT,
    SUM(P.SUM_STARTCOUNT) AS SUM_STARTCOUNT,
    SUM(P.SUM_WAGERATE) AS SUM_WAGERATE,
    SUM(P.SUM_WAGECOST) AS SUM_WAGECOST,
    SUM(P.SUM_OVERTIMEWAGECOST) AS SUM_OVERTIMEWAGECOST,
    SUM(P.SUM_OVERTIMEWAGERATE) AS SUM_OVERTIMEWAGERATE,
    SUM(P.SUM_GANGRUNBYQUANTITY) AS SUM_GANGRUNBYQUANTITY,
    SUM(P.SUM_BADQUANTITY) AS SUM_BADQUANTITY,
    SUM(P.SUM_POSTAGECOST) AS SUM_POSTAGECOST,
    SUM(P.SUM_PLANNEDWASTE) AS SUM_PLANNEDWASTE,
    SUM(P.SUM_WIPRATE) AS SUM_WIPRATE,
    SUM(P.SUM_WIPCOST) AS SUM_WIPCOST,
    SUM(P.SUM_INLINEOPRATE) AS SUM_INLINEOPRATE,
    SUM(P.SUM_INLINEOPCOST) AS SUM_INLINEOPCOST,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.MART_REVENUE.V_PRODUCTION_GROUPED P
INNER JOIN DATA_VALIDATION.RAW_SQL_SERVER.PRODUCTIONJOBNUMBER PJ
    ON P.CODE = PJ.PRODUCTIONCODE

GROUP BY
    P.CODE,
    PJ.JOBNUMBER,
    PJ.COMPONENTNUMBER,
    P.STARTDATE,
    P.EMPLOYEECODE,
    P.PROCESSCODE,
    P.COMPLETIONCODE,
    P.REASONCODE,
    P.COSTCODE,
    P.GANGRUN,
    P.ENTRYDATE,
    P.DEPARTMENTCODE,
    P.CREATEDATIM,
    P.UPDATEDATIM,
    P.GANGRUNBYAREA,
    P.POSTEDTOGL,
    P.GRJOBNUMBER,
    P.CREWLEADERPROCESSCODE,
    P.GANGCOMPONENTNUMBER;;
