create or replace view V_POLINEITEM_ANALYTICS(
	PONUMBER,
	ITEMNUMBER,
	MATERIALCODE,
	PRODUCTID,
	JOBNUMBER,
	COMPONENTNUMBER,
	GLACCOUNT,
	GLSUBACCOUNT,
	COSTCODE,
	LOCATIONCODE,
	GLCOGACCOUNT,
	GLWIPCODE,
	CURRENCYCODE,
	DUE_DATE,
	ENTRY_DATE,
	INVOICE_DATE,
	FIRST_CREATEDATIM,
	LAST_UPDATEDATIM,
	TOTAL_QUANTITY,
	TOTAL_UNITCOST,
	TOTAL_EXTENDEDCOST,
	TOTAL_FIXEDQUANTITY,
	TOTAL_FIXEDUNITCOST,
	TOTAL_TAXAMOUNT,
	TOTAL_ROLLWEIGHT,
	TOTAL_UNITCOSTFOREIGN,
	TOTAL_EXTENDEDCOSTFOREIGN,
	TOTAL_FIXEDUNITCOSTFOREIGN,
	ROW_COUNT
) as
SELECT
    PONUMBER,
    ITEMNUMBER,
    MATERIALCODE,
    PRODUCTID,
    JOBNUMBER,
    COMPONENTNUMBER,
    GLACCOUNT,
    GLSUBACCOUNT,
    COSTCODE,
    LOCATIONCODE,
    GLCOGACCOUNT,
    GLWIPCODE,
    CURRENCYCODE,

    MIN(DUEDATE) AS DUE_DATE,
    MIN(ENTRYDATE) AS ENTRY_DATE,
    MIN(INVOICEDATE) AS INVOICE_DATE,
    MIN(CREATEDATIM) AS FIRST_CREATEDATIM,
    MAX(UPDATEDATIM) AS LAST_UPDATEDATIM,

    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(UNITCOST) AS TOTAL_UNITCOST,
    SUM(EXTENDEDCOST) AS TOTAL_EXTENDEDCOST,
    SUM(FIXEDQUANTITY) AS TOTAL_FIXEDQUANTITY,
    SUM(FIXEDUNITCOST) AS TOTAL_FIXEDUNITCOST,
    SUM(TAXAMOUNT) AS TOTAL_TAXAMOUNT,
    SUM(ROLLWEIGHT) AS TOTAL_ROLLWEIGHT,
    SUM(UNITCOSTFOREIGN) AS TOTAL_UNITCOSTFOREIGN,
    SUM(EXTENDEDCOSTFOREIGN) AS TOTAL_EXTENDEDCOSTFOREIGN,
    SUM(FIXEDUNITCOSTFOREIGN) AS TOTAL_FIXEDUNITCOSTFOREIGN,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.POLINEITEM
GROUP BY
    PONUMBER,
    ITEMNUMBER,
    MATERIALCODE,
    PRODUCTID,
    JOBNUMBER,
    COMPONENTNUMBER,
    GLACCOUNT,
    GLSUBACCOUNT,
    COSTCODE,
    LOCATIONCODE,
    GLCOGACCOUNT,
    GLWIPCODE,
    CURRENCYCODE;;
