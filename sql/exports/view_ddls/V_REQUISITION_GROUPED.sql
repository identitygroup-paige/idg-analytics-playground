create or replace view V_REQUISITION_GROUPED(
	CODE,
	JOBNUMBER,
	COMPONENTNUMBER,
	MATERIALCODE,
	GLACCOUNT,
	VENDORPRODUCTID,
	COSTINGMETHOD,
	LINEITEMTYPE,
	ENTRYDATE,
	VENDORID,
	LOCATIONCODE,
	MULTILOCATION,
	PLANTID,
	DUEDATE,
	CREATEDATIM,
	UPDATEDATIM,
	MANUFACTURERITEMNUMBER,
	SUM_QUANTITY,
	SUM_UNITCOST,
	SUM_EXTENDEDCOST,
	SUM_FIXEDQUANTITY,
	SUM_FIXEDUNITCOST,
	SUM_QUANTITYTOORDER,
	ROW_COUNT
) as
SELECT
    CODE,
    JOBNUMBER,
    COMPONENTNUMBER,
    MATERIALCODE,
    GLACCOUNT,
    VENDORPRODUCTID,
    COSTINGMETHOD,
    LINEITEMTYPE,
    ENTRYDATE,
    VENDORID,
    LOCATIONCODE,
    MULTILOCATION,
    PLANTID,
    DUEDATE,
    CREATEDATIM,
    UPDATEDATIM,
    MANUFACTURERITEMNUMBER,

    SUM(QUANTITY) AS SUM_QUANTITY,
    SUM(UNITCOST) AS SUM_UNITCOST,
    SUM(EXTENDEDCOST) AS SUM_EXTENDEDCOST,
    SUM(FIXEDQUANTITY) AS SUM_FIXEDQUANTITY,
    SUM(FIXEDUNITCOST) AS SUM_FIXEDUNITCOST,
    SUM(QUANTITYTOORDER) AS SUM_QUANTITYTOORDER,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.REQUISITION
GROUP BY
    CODE,
    JOBNUMBER,
    COMPONENTNUMBER,
    MATERIALCODE,
    GLACCOUNT,
    VENDORPRODUCTID,
    COSTINGMETHOD,
    LINEITEMTYPE,
    ENTRYDATE,
    VENDORID,
    LOCATIONCODE,
    MULTILOCATION,
    PLANTID,
    DUEDATE,
    CREATEDATIM,
    UPDATEDATIM,
    MANUFACTURERITEMNUMBER;;
