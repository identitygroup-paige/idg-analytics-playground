create or replace view V_PORECEIPT_ANALYTICS(
	PONUMBER,
	ITEMNUMBER,
	JOBNUMBER,
	LOCATIONCODE,
	ROLLID,
	LOTNUMBER,
	PALLETCODE,
	FIRST_RECEIVEDATE,
	LAST_RECEIVEDATE,
	ENTRY_DATE,
	INVOICE_DATE,
	FIRST_CREATEDATIM,
	LAST_UPDATEDATIM,
	TOTAL_QUANTITY,
	TOTAL_UNITCOST,
	TOTAL_MISCCOST,
	TOTAL_EXTENDEDCOST,
	TOTAL_WIDTH,
	TOTAL_ROLLLENGTH,
	TOTAL_TAXAMOUNT,
	TOTAL_FREIGHTCOST,
	TOTAL_ROLLWIDTH,
	TOTAL_ROLLWEIGHT,
	TOTAL_RETURNEDQUANTITY,
	TOTAL_PLACEINCONSIGNMENT,
	TOTAL_PALLETSEQUENCENUMBER,
	RECEIPT_ROW_COUNT,
	DISTINCT_RECEIPT_COUNT
) as
SELECT
    PONUMBER,
    ITEMNUMBER,
    JOBNUMBER,
    LOCATIONCODE,
    ROLLID,
    LOTNUMBER,
    PALLETCODE,

    MIN(RECEIVEDATE) AS FIRST_RECEIVEDATE,
    MAX(RECEIVEDATE) AS LAST_RECEIVEDATE,
    MIN(ENTRYDATE) AS ENTRY_DATE,
    MIN(INVOICEDATE) AS INVOICE_DATE,
    MIN(CREATEDATIM) AS FIRST_CREATEDATIM,
    MAX(UPDATEDATIM) AS LAST_UPDATEDATIM,

    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(UNITCOST) AS TOTAL_UNITCOST,
    SUM(MISCCOST) AS TOTAL_MISCCOST,
    SUM(EXTENDEDCOST) AS TOTAL_EXTENDEDCOST,
    SUM(WIDTH) AS TOTAL_WIDTH,
    SUM(ROLLLENGTH) AS TOTAL_ROLLLENGTH,
    SUM(TAXAMOUNT) AS TOTAL_TAXAMOUNT,
    SUM(FREIGHTCOST) AS TOTAL_FREIGHTCOST,
    SUM(ROLLWIDTH) AS TOTAL_ROLLWIDTH,
    SUM(ROLLWEIGHT) AS TOTAL_ROLLWEIGHT,
    SUM(RETURNEDQUANTITY) AS TOTAL_RETURNEDQUANTITY,
    SUM(PLACEINCONSIGNMENT) AS TOTAL_PLACEINCONSIGNMENT,
    SUM(PALLETSEQUENCENUMBER) AS TOTAL_PALLETSEQUENCENUMBER,

    COUNT(*) AS RECEIPT_ROW_COUNT,
    COUNT(DISTINCT RECEIPTNUMBER) AS DISTINCT_RECEIPT_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.PORECEIPT
GROUP BY
    PONUMBER,
    ITEMNUMBER,
    JOBNUMBER,
    LOCATIONCODE,
    ROLLID,
    LOTNUMBER,
    PALLETCODE;;
