create or replace view V_MONTHLY_REVENUE_SAMPLE(
	REVENUE_MONTH,
	POST_DATE,
	TRANSACTION_DATE,
	LINE_ORDER_DATE,
	JOB_ORDER_DATE,
	JOB_DUE_DATE,
	JOB_COMPLETE_DATE,
	CUSTACCOUNT,
	CUSTNAME,
	JOBNUMBER,
	JOBDESCRIPTION,
	ORDERTYPE,
	JOBSTATUS,
	PLANTID,
	SALESREPCODE,
	CSR,
	ESTIMATOR,
	TRANSACTIONNUMBER,
	DOCUMENTNUMBER,
	TRANSACTIONTYPE,
	AR_STATUS,
	TERMSCODE,
	AR_SALESREPCODE,
	COMPANYID,
	TRANSACTIONLINENUMBER,
	LINETYPE,
	LINE_DESCRIPTION,
	PONUMBER,
	QTY_ORDERED,
	QTY_SHIPPED,
	UNIT_PRICE_SUM,
	EXTENDED_VALUE,
	DISCOUNT_VALUE,
	NET_REVENUE,
	TAX_AMOUNT,
	TOTAL_VALUE,
	COST_VALUE,
	GROSS_MARGIN,
	CURRENCYCODE,
	EXCHANGERATE
) as
SELECT
    DATE_TRUNC(
        'MONTH',
        COALESCE(
            TRY_TO_TIMESTAMP_NTZ(ar.POSTDATE),
            TRY_TO_TIMESTAMP_NTZ(ar.TRANSACTIONDATE),
            TRY_TO_TIMESTAMP_NTZ(atl.ORDERDATE)
        )
    ) AS REVENUE_MONTH,

    TRY_TO_TIMESTAMP_NTZ(ar.POSTDATE) AS POST_DATE,
    TRY_TO_TIMESTAMP_NTZ(ar.TRANSACTIONDATE) AS TRANSACTION_DATE,
    TRY_TO_TIMESTAMP_NTZ(atl.ORDERDATE) AS LINE_ORDER_DATE,
    TRY_TO_TIMESTAMP_NTZ(oh.ORDERDATE) AS JOB_ORDER_DATE,
    TRY_TO_TIMESTAMP_NTZ(oh.DUEDATE) AS JOB_DUE_DATE,
    TRY_TO_TIMESTAMP_NTZ(oh.COMPLETEDATE) AS JOB_COMPLETE_DATE,

    oh.CUSTACCOUNT,
    oh.CUSTNAME,
    oh.JOBNUMBER,
    oh.JOBDESCRIPTION,
    oh.ORDERTYPE,
    oh.JOBSTATUS,
    oh.PLANTID,
    oh.SALESREPCODE,
    oh.CSR,
    oh.ESTIMATOR,

    ar.TRANSACTIONNUMBER,
    ar.DOCUMENTNUMBER,
    ar.TRANSACTIONTYPE,
    ar.STATUS AS AR_STATUS,
    ar.TERMSCODE,
    ar.SALESREPCODE AS AR_SALESREPCODE,
    ar.COMPANYID,

    atl.TRANSACTIONLINENUMBER,
    atl.LINETYPE,
    atl.DESCRIPTION AS LINE_DESCRIPTION,
    atl.PONUMBER,

    SUM(atl.QTYORDERED) AS QTY_ORDERED,
    SUM(atl.QTYSHIPPED) AS QTY_SHIPPED,
    SUM(atl.UNITPRICE) AS UNIT_PRICE_SUM,
    SUM(atl.EXTENDEDVAL) AS EXTENDED_VALUE,
    SUM(atl.DISCOUNTVAL) AS DISCOUNT_VALUE,
    SUM(atl.NETVAL) AS NET_REVENUE,
    SUM(atl.TAXVAL) AS TAX_AMOUNT,
    SUM(atl.TOTALVAL) AS TOTAL_VALUE,
    SUM(atl.COSTVAL) AS COST_VALUE,
    SUM(atl.NETVAL) - SUM(atl.COSTVAL) AS GROSS_MARGIN,

    atl.CURRENCYCODE,
    atl.EXCHANGERATE

FROM DATA_VALIDATION.DATA_VALIDATION_DEV.COORD_ARTRANSACTIONLINE_SAMPLE atl

LEFT JOIN DATA_VALIDATION.DATA_VALIDATION_DEV.COORD_ARTRANSACTION_SAMPLE ar
    ON atl.TRANSACTIONNUMBER = ar.TRANSACTIONNUMBER

LEFT JOIN DATA_VALIDATION.DATA_VALIDATION_DEV.COORD_ORDERHEADER_SAMPLE oh
    ON atl.JOBNUMBER = oh.JOBNUMBER

GROUP BY
    REVENUE_MONTH,
    POST_DATE,
    TRANSACTION_DATE,
    LINE_ORDER_DATE,
    JOB_ORDER_DATE,
    JOB_DUE_DATE,
    JOB_COMPLETE_DATE,
    oh.CUSTACCOUNT,
    oh.CUSTNAME,
    oh.JOBNUMBER,
    oh.JOBDESCRIPTION,
    oh.ORDERTYPE,
    oh.JOBSTATUS,
    oh.PLANTID,
    oh.SALESREPCODE,
    oh.CSR,
    oh.ESTIMATOR,
    ar.TRANSACTIONNUMBER,
    ar.DOCUMENTNUMBER,
    ar.TRANSACTIONTYPE,
    ar.STATUS,
    ar.TERMSCODE,
    ar.SALESREPCODE,
    ar.COMPANYID,
    atl.TRANSACTIONLINENUMBER,
    atl.LINETYPE,
    atl.DESCRIPTION,
    atl.PONUMBER,
    atl.CURRENCYCODE,
    atl.EXCHANGERATE;;
