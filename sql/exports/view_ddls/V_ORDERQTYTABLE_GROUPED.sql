	JOBNUMBER,
	COMPONENTNUMBER,
	ID,
	COMPONENTID,
	QUANTITYLINENO,
	ESTIMATENUMBER,
	CREATEDATIM,
	UPDATEDATIM,
	SUM_QUANTITY,
	SUM_PRODUCTIONMARKUP,
	SUM_MATERIALMARKUP,
	SUM_STOCKMARKUP,
	SUM_MANUALPRICE,
	SUM_PRODUCTIONCOST,
	SUM_MATERIALCOST,
	SUM_STOCKCOST,
	SUM_OSCOST,
	SUM_TOTALMINUTES,
	SUM_TOTALCOST,
	SUM_TOTALPRICE,
	SUM_PRODUCTIONPRICE,
	SUM_MATERIALPRICE,
	SUM_STOCKPRICE,
	SUM_OSPRICE,
	SUM_ADDCOLORCOST,
	SUM_ADDCOLORPRICE,
	SUM_ADDCOLORMATCOST,
	SUM_ADDCOLORMATPRICE,
	SUM_GRIDPRICE,
	SUM_COMMISSIONAMOUNT,
	SUM_ADDMCOST,
	SUM_ADDMPRICE,
	SUM_TAXAMOUNTA,
	SUM_TAXAMOUNTB,
	SUM_TAXAMOUNTC,
	SUM_TAXAMOUNTD,
	SUM_DISCOUNTAMOUNT,
	SUM_QUANTITYPERPACKAGE,
	SUM_SETPRODUCTIONMARKUP,
