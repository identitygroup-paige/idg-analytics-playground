	SUM_SETOSSPRICE,
	SUM_SETTOTALPRICE,
	SUM_SETPROFITDOLLARS,
	SUM_MANUALUNITPRICE,
	SUM_AIPRODUCTIONCOST,
	SUM_COMBOUNITCOST,
	SUM_COMBOUNITPRICE,
	SUM_TAXOVERRIDEAMOUNT,
	SUM_UNITPRICE,
	SUM_ROYALTYAMOUNT,
	ROW_COUNT
) as
SELECT
    JOBNUMBER,
    COMPONENTNUMBER,
    ID,
    COMPONENTID,
    QUANTITYLINENO,
    ESTIMATENUMBER,
    CREATEDATIM,
    UPDATEDATIM,

    SUM(QUANTITY) AS SUM_QUANTITY,
    SUM(PRODUCTIONMARKUP) AS SUM_PRODUCTIONMARKUP,
    SUM(MATERIALMARKUP) AS SUM_MATERIALMARKUP,
    SUM(STOCKMARKUP) AS SUM_STOCKMARKUP,
    SUM(MANUALPRICE) AS SUM_MANUALPRICE,

    SUM(PRODUCTIONCOST) AS SUM_PRODUCTIONCOST,
    SUM(MATERIALCOST) AS SUM_MATERIALCOST,
    SUM(STOCKCOST) AS SUM_STOCKCOST,
    SUM(OSCOST) AS SUM_OSCOST,

    SUM(TOTALMINUTES) AS SUM_TOTALMINUTES,
    SUM(TOTALCOST) AS SUM_TOTALCOST,
    SUM(TOTALPRICE) AS SUM_TOTALPRICE,

    SUM(PRODUCTIONPRICE) AS SUM_PRODUCTIONPRICE,
    SUM(MATERIALPRICE) AS SUM_MATERIALPRICE,
    SUM(STOCKPRICE) AS SUM_STOCKPRICE,
    SUM(OSPRICE) AS SUM_OSPRICE,

    SUM(ADDCOLORCOST) AS SUM_ADDCOLORCOST,
    SUM(ADDCOLORPRICE) AS SUM_ADDCOLORPRICE,
    SUM(ADDCOLORMATCOST) AS SUM_ADDCOLORMATCOST,
    SUM(ADDCOLORMATPRICE) AS SUM_ADDCOLORMATPRICE,

    SUM(GRIDPRICE) AS SUM_GRIDPRICE,
    SUM(COMMISSIONAMOUNT) AS SUM_COMMISSIONAMOUNT,

    SUM(ADDMCOST) AS SUM_ADDMCOST,
    SUM(ADDMPRICE) AS SUM_ADDMPRICE,

    SUM(TAXAMOUNTA) AS SUM_TAXAMOUNTA,
    SUM(TAXAMOUNTB) AS SUM_TAXAMOUNTB,
    SUM(TAXAMOUNTC) AS SUM_TAXAMOUNTC,
    SUM(TAXAMOUNTD) AS SUM_TAXAMOUNTD,

    SUM(DISCOUNTAMOUNT) AS SUM_DISCOUNTAMOUNT,
    SUM(QUANTITYPERPACKAGE) AS SUM_QUANTITYPERPACKAGE,

    SUM(SETPRODUCTIONMARKUP) AS SUM_SETPRODUCTIONMARKUP,
    SUM(SETMATERIALMARKUP) AS SUM_SETMATERIALMARKUP,
    SUM(SETPAPERMARKUP) AS SUM_SETPAPERMARKUP,
    SUM(SETOSSMARKUP) AS SUM_SETOSSMARKUP,

    SUM(SETPRODUCTIONPRICE) AS SUM_SETPRODUCTIONPRICE,
    SUM(SETMATERIALPRICE) AS SUM_SETMATERIALPRICE,
    SUM(SETPAPERPRICE) AS SUM_SETPAPERPRICE,
    SUM(SETOSSPRICE) AS SUM_SETOSSPRICE,

    SUM(SETTOTALPRICE) AS SUM_SETTOTALPRICE,
    SUM(SETPROFITDOLLARS) AS SUM_SETPROFITDOLLARS,

    SUM(MANUALUNITPRICE) AS SUM_MANUALUNITPRICE,
    SUM(AIPRODUCTIONCOST) AS SUM_AIPRODUCTIONCOST,
    SUM(COMBOUNITCOST) AS SUM_COMBOUNITCOST,
    SUM(COMBOUNITPRICE) AS SUM_COMBOUNITPRICE,
    SUM(TAXOVERRIDEAMOUNT) AS SUM_TAXOVERRIDEAMOUNT,
    SUM(UNITPRICE) AS SUM_UNITPRICE,
    SUM(ROYALTYAMOUNT) AS SUM_ROYALTYAMOUNT,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERQTYTABLE
GROUP BY
    JOBNUMBER,
    COMPONENTNUMBER,
    ID,
    COMPONENTID,
    QUANTITYLINENO,
    ESTIMATENUMBER,
    CREATEDATIM,
    UPDATEDATIM;;
