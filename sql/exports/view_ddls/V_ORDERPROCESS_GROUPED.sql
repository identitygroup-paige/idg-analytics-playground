create or replace view V_ORDERPROCESS_GROUPED(
	JOBNUMBER,
	COMPONENTNUMBER,
	GLACCOUNT,
	GLCOGACCOUNT,
	GROUPNO,
	ITEMNUMBER,
	PARTNUMBER,
	PROCESSCODE,
	MATERIALCODE,
	VENDORID,
	VENDORNAME,
	VENDORPRODUCTID,
	DIFFICULTY,
	CHANGEORDER,
	ENTRYDATE,
	CHANGEDATE,
	CREATEDATIM,
	UPDATEDATIM,
	APPROVALCODE,
	DUEDATE,
	COSTINGMETHOD,
	ESTIMATENUMBER,
	CHANGEORDERID,
	FORMPARTNUMBER,
	USERDEFINED1,
	USERDEFINED2,
	USERDEFINED3,
	USERDEFINED4,
	USERDEFINED5,
	DONTINVOICEITEM,
	RUSHCHARGE,
	MULTIPLYBYPARTS,
	ID,
	PROCESSID,
	COMPONENTID,
	SUM_UNITSPERCYCLE,
	SUM_FIXEDMARKUP,
	SUM_FIXEDCOST,
	SUM_FIXEDQUANTITY,
	SUM_ADDITIONALCHARGE,
	SUM_FIXEDUNITCOST,
	SUM_DISCOUNT,
	SUM_PRODUCTIONQUANTITY,
	SUM_ADDTOTEMPLATEPRICE,
	SUM_UNITCOSTOVERRIDE,
	SUM_USERATEOVERRIDEASPRICE,
	SUM_OVERRIDEUNITSPERCYCLE,
	ROW_COUNT
) as
SELECT
    JOBNUMBER,
    COMPONENTNUMBER,
    GLACCOUNT,
    GLCOGACCOUNT,
    GROUPNO,
    ITEMNUMBER,
    PARTNUMBER,
    PROCESSCODE,
    MATERIALCODE,
    VENDORID,
    VENDORNAME,
    VENDORPRODUCTID,
    DIFFICULTY,
    CHANGEORDER,
    ENTRYDATE,
    CHANGEDATE,
    CREATEDATIM,
    UPDATEDATIM,
    APPROVALCODE,
    DUEDATE,
    COSTINGMETHOD,
    ESTIMATENUMBER,
    CHANGEORDERID,
    FORMPARTNUMBER,
    USERDEFINED1,
    USERDEFINED2,
    USERDEFINED3,
    USERDEFINED4,
    USERDEFINED5,
    DONTINVOICEITEM,
    RUSHCHARGE,
    MULTIPLYBYPARTS,
    ID,
    PROCESSID,
    COMPONENTID,

    SUM(UNITSPERCYCLE) AS SUM_UNITSPERCYCLE,
    SUM(FIXEDMARKUP) AS SUM_FIXEDMARKUP,
    SUM(FIXEDCOST) AS SUM_FIXEDCOST,
    SUM(FIXEDQUANTITY) AS SUM_FIXEDQUANTITY,
    SUM(ADDITIONALCHARGE) AS SUM_ADDITIONALCHARGE,
    SUM(FIXEDUNITCOST) AS SUM_FIXEDUNITCOST,
    SUM(DISCOUNT) AS SUM_DISCOUNT,
    SUM(PRODUCTIONQUANTITY) AS SUM_PRODUCTIONQUANTITY,
    SUM(ADDTOTEMPLATEPRICE) AS SUM_ADDTOTEMPLATEPRICE,
    SUM(UNITCOSTOVERRIDE) AS SUM_UNITCOSTOVERRIDE,
    SUM(USERATEOVERRIDEASPRICE) AS SUM_USERATEOVERRIDEASPRICE,
    SUM(OVERRIDEUNITSPERCYCLE) AS SUM_OVERRIDEUNITSPERCYCLE,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERPROCESS
GROUP BY
    JOBNUMBER,
    COMPONENTNUMBER,
    GLACCOUNT,
    GLCOGACCOUNT,
    GROUPNO,
    ITEMNUMBER,
    PARTNUMBER,
    PROCESSCODE,
    MATERIALCODE,
    VENDORID,
    VENDORNAME,
    VENDORPRODUCTID,
    DIFFICULTY,
    CHANGEORDER,
    ENTRYDATE,
    CHANGEDATE,
    CREATEDATIM,
    UPDATEDATIM,
    APPROVALCODE,
    DUEDATE,
    COSTINGMETHOD,
    ESTIMATENUMBER,
    CHANGEORDERID,
    FORMPARTNUMBER,
    USERDEFINED1,
    USERDEFINED2,
    USERDEFINED3,
    USERDEFINED4,
    USERDEFINED5,
    DONTINVOICEITEM,
    RUSHCHARGE,
    MULTIPLYBYPARTS,
    ID,
    PROCESSID,
    COMPONENTID;;
