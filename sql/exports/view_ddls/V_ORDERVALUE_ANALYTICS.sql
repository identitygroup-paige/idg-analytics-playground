create or replace view V_ORDERVALUE_ANALYTICS(
	JOBNUMBER,
	ESTIMATENUMBER,
	COMPONENTNUMBER,
	GROUPNO,
	ITEMNUMBER,
	PARTNUMBER,
	QUANTITYLINENO,
	PROCESSID,
	QTYTABLEID,
	PLANTID,
	GLACCOUNT,
	TOTAL_PRODUCTIONQUANTITY,
	TOTAL_MATERIALQUANTITY,
	TOTAL_PRODUCTIONMINUTES,
	TOTAL_PRODUCTIONCOST,
	TOTAL_MATERIALCOST,
	TOTAL_OSCOST,
	TOTAL_PRODUCTIONMARKUP,
	TOTAL_MATERIALMARKUP,
	TOTAL_OSMARKUP,
	TOTAL_PRODUCTIONPRICE,
	TOTAL_MATERIALPRICE,
	TOTAL_OSPRICE,
	TOTAL_UNITCOST,
	TOTAL_ADDCOLORCOST,
	TOTAL_ADDCOLORPRICE,
	TOTAL_ADDMCOST,
	TOTAL_ADDMPRICE,
	TOTAL_STOCKPOUNDS,
	TOTAL_NETPOUNDS,
	TOTAL_PRODUCTIONSPOILAGE,
	TOTAL_MATERIALSPOILAGE,
	TOTAL_SIDEONEQUANTITY,
	TOTAL_SIDETWOQUANTITY,
	TOTAL_ADDCOLORMATCOST,
	TOTAL_ADDCOLORMATPRICE,
	TOTAL_PERCENTAGE,
	TOTAL_JOBPERCENTAGE,
	TOTAL_ROLLCHANGES,
	TOTAL_DMPRODUCTIONCOST,
	TOTAL_GROSSCOUNT,
	TOTAL_NETCOUNT,
	TOTAL_BINDERYCOUNT,
	TOTAL_MRCOUNT,
	TOTAL_AIPRODUCTIONCOST,
	TOTAL_SPOILAGEPERCENTAGE,
	TOTAL_INPUTQUANTITY,
	TOTAL_OUTPUTQUANTITY,
	TOTAL_MRSPOILAGEPERCENTAGE,
	TOTAL_MRSPOILAGE,
	TOTAL_CLICKCOST,
	TOTAL_SETUPMINUTES,
	TOTAL_SPEEDOVERRIDE,
	TOTAL_MRSPOILAGEOVERRIDE,
	TOTAL_RUNSPOILAGEOVERRIDE,
	TOTAL_GROUPPERCENTAGE,
	TOTAL_ROYALTYAMOUNT,
	FIRST_ENTRYDATE,
	LAST_ENTRYDATE,
	FIRST_CREATEDATIM,
	LAST_UPDATEDATIM,
	ROW_COUNT
) as
SELECT
    JOBNUMBER,
    ESTIMATENUMBER,
    COMPONENTNUMBER,
    GROUPNO,
    ITEMNUMBER,
    PARTNUMBER,
    QUANTITYLINENO,
    PROCESSID,
    QTYTABLEID,
    PLANTID,
    GLACCOUNT,

    SUM(PRODUCTIONQUANTITY) AS TOTAL_PRODUCTIONQUANTITY,
    SUM(MATERIALQUANTITY) AS TOTAL_MATERIALQUANTITY,
    SUM(PRODUCTIONMINUTES) AS TOTAL_PRODUCTIONMINUTES,
    SUM(PRODUCTIONCOST) AS TOTAL_PRODUCTIONCOST,
    SUM(MATERIALCOST) AS TOTAL_MATERIALCOST,
    SUM(OSCOST) AS TOTAL_OSCOST,

    SUM(PRODUCTIONMARKUP) AS TOTAL_PRODUCTIONMARKUP,
    SUM(MATERIALMARKUP) AS TOTAL_MATERIALMARKUP,
    SUM(OSMARKUP) AS TOTAL_OSMARKUP,

    SUM(PRODUCTIONPRICE) AS TOTAL_PRODUCTIONPRICE,
    SUM(MATERIALPRICE) AS TOTAL_MATERIALPRICE,
    SUM(OSPRICE) AS TOTAL_OSPRICE,

    SUM(UNITCOST) AS TOTAL_UNITCOST,
    SUM(ADDCOLORCOST) AS TOTAL_ADDCOLORCOST,
    SUM(ADDCOLORPRICE) AS TOTAL_ADDCOLORPRICE,
    SUM(ADDMCOST) AS TOTAL_ADDMCOST,
    SUM(ADDMPRICE) AS TOTAL_ADDMPRICE,

    SUM(STOCKPOUNDS) AS TOTAL_STOCKPOUNDS,
    SUM(NETPOUNDS) AS TOTAL_NETPOUNDS,

    SUM(PRODUCTIONSPOILAGE) AS TOTAL_PRODUCTIONSPOILAGE,
    SUM(MATERIALSPOILAGE) AS TOTAL_MATERIALSPOILAGE,

    SUM(SIDEONEQUANTITY) AS TOTAL_SIDEONEQUANTITY,
    SUM(SIDETWOQUANTITY) AS TOTAL_SIDETWOQUANTITY,

    SUM(ADDCOLORMATCOST) AS TOTAL_ADDCOLORMATCOST,
    SUM(ADDCOLORMATPRICE) AS TOTAL_ADDCOLORMATPRICE,

    SUM(PERCENTAGE) AS TOTAL_PERCENTAGE,
    SUM(JOBPERCENTAGE) AS TOTAL_JOBPERCENTAGE,
    SUM(ROLLCHANGES) AS TOTAL_ROLLCHANGES,

    SUM(DMPRODUCTIONCOST) AS TOTAL_DMPRODUCTIONCOST,
    SUM(GROSSCOUNT) AS TOTAL_GROSSCOUNT,
    SUM(NETCOUNT) AS TOTAL_NETCOUNT,
    SUM(BINDERYCOUNT) AS TOTAL_BINDERYCOUNT,
    SUM(MRCOUNT) AS TOTAL_MRCOUNT,
    SUM(AIPRODUCTIONCOST) AS TOTAL_AIPRODUCTIONCOST,

    SUM(SPOILAGEPERCENTAGE) AS TOTAL_SPOILAGEPERCENTAGE,
    SUM(INPUTQUANTITY) AS TOTAL_INPUTQUANTITY,
    SUM(OUTPUTQUANTITY) AS TOTAL_OUTPUTQUANTITY,
    SUM(MRSPOILAGEPERCENTAGE) AS TOTAL_MRSPOILAGEPERCENTAGE,
    SUM(MRSPOILAGE) AS TOTAL_MRSPOILAGE,
    SUM(CLICKCOST) AS TOTAL_CLICKCOST,

    SUM(SETUPMINUTES) AS TOTAL_SETUPMINUTES,
    SUM(SPEEDOVERRIDE) AS TOTAL_SPEEDOVERRIDE,
    SUM(MRSPOILAGEOVERRIDE) AS TOTAL_MRSPOILAGEOVERRIDE,
    SUM(RUNSPOILAGEOVERRIDE) AS TOTAL_RUNSPOILAGEOVERRIDE,

    SUM(GROUPPERCENTAGE) AS TOTAL_GROUPPERCENTAGE,
    SUM(ROYALTYAMOUNT) AS TOTAL_ROYALTYAMOUNT,

    MIN(ENTRYDATE) AS FIRST_ENTRYDATE,
    MAX(ENTRYDATE) AS LAST_ENTRYDATE,
    MIN(CREATEDATIM) AS FIRST_CREATEDATIM,
    MAX(UPDATEDATIM) AS LAST_UPDATEDATIM,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERVALUE
GROUP BY
    JOBNUMBER,
    ESTIMATENUMBER,
    COMPONENTNUMBER,
    GROUPNO,
    ITEMNUMBER,
    PARTNUMBER,
    QUANTITYLINENO,
    PROCESSID,
    QTYTABLEID,
    PLANTID,
    GLACCOUNT;;
