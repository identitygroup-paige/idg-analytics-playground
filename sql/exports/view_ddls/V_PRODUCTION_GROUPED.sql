create or replace view V_PRODUCTION_GROUPED(
	CODE,
	STARTDATE,
	EMPLOYEECODE,
	PROCESSCODE,
	COMPLETIONCODE,
	REASONCODE,
	COSTCODE,
	GANGRUN,
	ENTRYDATE,
	DEPARTMENTCODE,
	CREATEDATIM,
	UPDATEDATIM,
	GANGRUNBYAREA,
	POSTEDTOGL,
	GRJOBNUMBER,
	CREWLEADERPROCESSCODE,
	GANGCOMPONENTNUMBER,
	SUM_QUANTITY,
	SUM_ELAPSEDTIME,
	SUM_CONCURRENT,
	SUM_AIRATE,
	SUM_DMRATE,
	SUM_OVERTIMEINCREASE,
	SUM_DOUBLETIMEINCREASE,
	SUM_UNITCOST,
	SUM_AICOST,
	SUM_DMCOST,
	SUM_TOTALCOPIES,
	SUM_GOODCOPIES,
	SUM_ACTUALWASTE,
	SUM_ENDCOUNT,
	SUM_STARTCOUNT,
	SUM_WAGERATE,
	SUM_WAGECOST,
	SUM_OVERTIMEWAGECOST,
	SUM_OVERTIMEWAGERATE,
	SUM_GANGRUNBYQUANTITY,
	SUM_BADQUANTITY,
	SUM_POSTAGECOST,
	SUM_PLANNEDWASTE,
	SUM_WIPRATE,
	SUM_WIPCOST,
	SUM_INLINEOPRATE,
	SUM_INLINEOPCOST,
	ROW_COUNT
) as
SELECT
    CODE,
    STARTDATE,
    EMPLOYEECODE,
    PROCESSCODE,
    COMPLETIONCODE,
    REASONCODE,
    COSTCODE,
    GANGRUN,
    ENTRYDATE,
    DEPARTMENTCODE,
    CREATEDATIM,
    UPDATEDATIM,
    GANGRUNBYAREA,
    POSTEDTOGL,
    GRJOBNUMBER,
    CREWLEADERPROCESSCODE,
    GANGCOMPONENTNUMBER,

    SUM(QUANTITY) AS SUM_QUANTITY,
    SUM(ELAPSEDTIME) AS SUM_ELAPSEDTIME,
    SUM(CONCURRENT) AS SUM_CONCURRENT,
    SUM(AIRATE) AS SUM_AIRATE,
    SUM(DMRATE) AS SUM_DMRATE,
    SUM(OVERTIMEINCREASE) AS SUM_OVERTIMEINCREASE,
    SUM(DOUBLETIMEINCREASE) AS SUM_DOUBLETIMEINCREASE,
    SUM(UNITCOST) AS SUM_UNITCOST,
    SUM(AICOST) AS SUM_AICOST,
    SUM(DMCOST) AS SUM_DMCOST,
    SUM(TOTALCOPIES) AS SUM_TOTALCOPIES,
    SUM(GOODCOPIES) AS SUM_GOODCOPIES,
    SUM(ACTUALWASTE) AS SUM_ACTUALWASTE,
    SUM(ENDCOUNT) AS SUM_ENDCOUNT,
    SUM(STARTCOUNT) AS SUM_STARTCOUNT,
    SUM(WAGERATE) AS SUM_WAGERATE,
    SUM(WAGECOST) AS SUM_WAGECOST,
    SUM(OVERTIMEWAGECOST) AS SUM_OVERTIMEWAGECOST,
    SUM(OVERTIMEWAGERATE) AS SUM_OVERTIMEWAGERATE,
    SUM(GANGRUNBYQUANTITY) AS SUM_GANGRUNBYQUANTITY,
    SUM(BADQUANTITY) AS SUM_BADQUANTITY,
    SUM(POSTAGECOST) AS SUM_POSTAGECOST,
    SUM(PLANNEDWASTE) AS SUM_PLANNEDWASTE,
    SUM(WIPRATE) AS SUM_WIPRATE,
    SUM(WIPCOST) AS SUM_WIPCOST,
    SUM(INLINEOPRATE) AS SUM_INLINEOPRATE,
    SUM(INLINEOPCOST) AS SUM_INLINEOPCOST,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.PRODUCTION
GROUP BY
    CODE,
    STARTDATE,
    EMPLOYEECODE,
    PROCESSCODE,
    COMPLETIONCODE,
    REASONCODE,
    COSTCODE,
    GANGRUN,
    ENTRYDATE,
    DEPARTMENTCODE,
    CREATEDATIM,
    UPDATEDATIM,
    GANGRUNBYAREA,
    POSTEDTOGL,
    GRJOBNUMBER,
    CREWLEADERPROCESSCODE,
    GANGCOMPONENTNUMBER;;
