create or replace view V_PROCESSSCHEDULE_GROUPED(
	CODE,
	JOBNUMBER,
	COMPONENTNUMBER,
	PROCESSCODE,
	COSTCENTERCODE,
	RUNSEQUENCE,
	STARTDATE,
	ENDDATE,
	STARTTIME,
	ENDTIME,
	DATECOMPLETED,
	COSTCENTERONLY,
	PRIORITYNUMBER,
	CREATEDATIM,
	UPDATEDATIM,
	GANGRUNCODE,
	ATTACHEDTOCODE,
	LOCKED,
	ORIGINALCOSTCENTER,
	ORIGINALHOURS,
	DONOTSCHEDULE,
	SUM_ESTIMATEDHOURS,
	SUM_SCHEDULEDHOURS,
	SUM_SCHEDULEDDAYS,
	SUM_BUFFERHOURS,
	SUM_COMPLETED,
	SUM_STARTDATEGAP,
	ROW_COUNT
) as
SELECT
    CODE,
    JOBNUMBER,
    COMPONENTNUMBER,
    PROCESSCODE,
    COSTCENTERCODE,
    RUNSEQUENCE,
    STARTDATE,
    ENDDATE,
    STARTTIME,
    ENDTIME,
    DATECOMPLETED,
    COSTCENTERONLY,
    PRIORITYNUMBER,
    CREATEDATIM,
    UPDATEDATIM,
    GANGRUNCODE,
    ATTACHEDTOCODE,
    LOCKED,
    ORIGINALCOSTCENTER,
    ORIGINALHOURS,
    DONOTSCHEDULE,

    SUM(ESTIMATEDHOURS) AS SUM_ESTIMATEDHOURS,
    SUM(SCHEDULEDHOURS) AS SUM_SCHEDULEDHOURS,
    SUM(SCHEDULEDDAYS) AS SUM_SCHEDULEDDAYS,
    SUM(BUFFERHOURS) AS SUM_BUFFERHOURS,
    SUM(COMPLETED) AS SUM_COMPLETED,
    SUM(STARTDATEGAP) AS SUM_STARTDATEGAP,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.PROCESSSCHEDULE
GROUP BY
    CODE,
    JOBNUMBER,
    COMPONENTNUMBER,
    PROCESSCODE,
    COSTCENTERCODE,
    RUNSEQUENCE,
    STARTDATE,
    ENDDATE,
    STARTTIME,
    ENDTIME,
    DATECOMPLETED,
    COSTCENTERONLY,
    PRIORITYNUMBER,
    CREATEDATIM,
    UPDATEDATIM,
    GANGRUNCODE,
    ATTACHEDTOCODE,
    LOCKED,
    ORIGINALCOSTCENTER,
    ORIGINALHOURS,
    DONOTSCHEDULE;;
