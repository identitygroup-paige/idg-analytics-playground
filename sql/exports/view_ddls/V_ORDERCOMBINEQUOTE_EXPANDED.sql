create or replace view V_ORDERCOMBINEQUOTE_EXPANDED(
	JOBNUMBER,
	ESTIMATENUMBER,
	ENTRYDATE,
	CREATEDATIM,
	UPDATEDATIM,
	SUM_TOTALPRICE1,
	SUM_TOTALPRICE2,
	SUM_TOTALPRICE3,
	SUM_TOTALPRICE4,
	SUM_TOTALPRICE5,
	SUM_TOTALPRICE6,
	SUM_ADDCOLORPRICE1,
	SUM_ADDCOLORPRICE2,
	SUM_ADDCOLORPRICE3,
	SUM_ADDCOLORPRICE4,
	SUM_ADDCOLORPRICE5,
	SUM_ADDCOLORPRICE6,
	SUM_ADDCOLORMATPRICE1,
	SUM_ADDCOLORMATPRICE2,
	SUM_ADDCOLORMATPRICE3,
	SUM_ADDCOLORMATPRICE4,
	SUM_ADDCOLORMATPRICE5,
	SUM_ADDCOLORMATPRICE6,
	SUM_ADDMPRICE1,
	SUM_ADDMPRICE2,
	SUM_ADDMPRICE3,
	SUM_ADDMPRICE4,
	SUM_ADDMPRICE5,
	SUM_ADDMPRICE6,
	SUM_TAXAMOUNT1,
	SUM_TAXAMOUNT2,
	SUM_TAXAMOUNT3,
	SUM_TAXAMOUNT4,
	SUM_TAXAMOUNT5,
	SUM_TAXAMOUNT6,
	SUM_DISCOUNTAMOUNT1,
	SUM_DISCOUNTAMOUNT2,
	SUM_DISCOUNTAMOUNT3,
	SUM_DISCOUNTAMOUNT4,
	SUM_DISCOUNTAMOUNT5,
	SUM_DISCOUNTAMOUNT6,
	SUM_QUANTITY1,
	SUM_QUANTITY2,
	SUM_QUANTITY3,
	SUM_QUANTITY4,
	SUM_QUANTITY5,
	SUM_QUANTITY6,
	SUM_CQUANTITY1,
	SUM_CQUANTITY2,
	SUM_CQUANTITY3,
	SUM_CQUANTITY4,
	SUM_CQUANTITY5,
	SUM_CQUANTITY6,
	ROW_COUNT
) as 
SELECT
    JOBNUMBER,
    ESTIMATENUMBER,
    ENTRYDATE,
    CREATEDATIM,
    UPDATEDATIM,

    SUM(TOTALPRICE1) AS SUM_TOTALPRICE1,
    SUM(TOTALPRICE2) AS SUM_TOTALPRICE2,
    SUM(TOTALPRICE3) AS SUM_TOTALPRICE3,
    SUM(TOTALPRICE4) AS SUM_TOTALPRICE4,
    SUM(TOTALPRICE5) AS SUM_TOTALPRICE5,
    SUM(TOTALPRICE6) AS SUM_TOTALPRICE6,

    SUM(ADDCOLORPRICE1) AS SUM_ADDCOLORPRICE1,
    SUM(ADDCOLORPRICE2) AS SUM_ADDCOLORPRICE2,
    SUM(ADDCOLORPRICE3) AS SUM_ADDCOLORPRICE3,
    SUM(ADDCOLORPRICE4) AS SUM_ADDCOLORPRICE4,
    SUM(ADDCOLORPRICE5) AS SUM_ADDCOLORPRICE5,
    SUM(ADDCOLORPRICE6) AS SUM_ADDCOLORPRICE6,

    SUM(ADDCOLORMATPRICE1) AS SUM_ADDCOLORMATPRICE1,
    SUM(ADDCOLORMATPRICE2) AS SUM_ADDCOLORMATPRICE2,
    SUM(ADDCOLORMATPRICE3) AS SUM_ADDCOLORMATPRICE3,
    SUM(ADDCOLORMATPRICE4) AS SUM_ADDCOLORMATPRICE4,
    SUM(ADDCOLORMATPRICE5) AS SUM_ADDCOLORMATPRICE5,
    SUM(ADDCOLORMATPRICE6) AS SUM_ADDCOLORMATPRICE6,

    SUM(ADDMPRICE1) AS SUM_ADDMPRICE1,
    SUM(ADDMPRICE2) AS SUM_ADDMPRICE2,
    SUM(ADDMPRICE3) AS SUM_ADDMPRICE3,
    SUM(ADDMPRICE4) AS SUM_ADDMPRICE4,
    SUM(ADDMPRICE5) AS SUM_ADDMPRICE5,
    SUM(ADDMPRICE6) AS SUM_ADDMPRICE6,

    SUM(TAXAMOUNT1) AS SUM_TAXAMOUNT1,
    SUM(TAXAMOUNT2) AS SUM_TAXAMOUNT2,
    SUM(TAXAMOUNT3) AS SUM_TAXAMOUNT3,
    SUM(TAXAMOUNT4) AS SUM_TAXAMOUNT4,
    SUM(TAXAMOUNT5) AS SUM_TAXAMOUNT5,
    SUM(TAXAMOUNT6) AS SUM_TAXAMOUNT6,

    SUM(DISCOUNTAMOUNT1) AS SUM_DISCOUNTAMOUNT1,
    SUM(DISCOUNTAMOUNT2) AS SUM_DISCOUNTAMOUNT2,
    SUM(DISCOUNTAMOUNT3) AS SUM_DISCOUNTAMOUNT3,
    SUM(DISCOUNTAMOUNT4) AS SUM_DISCOUNTAMOUNT4,
    SUM(DISCOUNTAMOUNT5) AS SUM_DISCOUNTAMOUNT5,
    SUM(DISCOUNTAMOUNT6) AS SUM_DISCOUNTAMOUNT6,

    SUM(QUANTITY1) AS SUM_QUANTITY1,
    SUM(QUANTITY2) AS SUM_QUANTITY2,
    SUM(QUANTITY3) AS SUM_QUANTITY3,
    SUM(QUANTITY4) AS SUM_QUANTITY4,
    SUM(QUANTITY5) AS SUM_QUANTITY5,
    SUM(QUANTITY6) AS SUM_QUANTITY6,

    SUM(CQUANTITY1) AS SUM_CQUANTITY1,
    SUM(CQUANTITY2) AS SUM_CQUANTITY2,
    SUM(CQUANTITY3) AS SUM_CQUANTITY3,
    SUM(CQUANTITY4) AS SUM_CQUANTITY4,
    SUM(CQUANTITY5) AS SUM_CQUANTITY5,
    SUM(CQUANTITY6) AS SUM_CQUANTITY6,

    COUNT(*) AS ROW_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERCOMBINEQUOTE
GROUP BY
    JOBNUMBER,
    ESTIMATENUMBER,
    ENTRYDATE,
    CREATEDATIM,
    UPDATEDATIM
ORDER BY
    JOBNUMBER,
    ESTIMATENUMBER,
    ENTRYDATE;;
