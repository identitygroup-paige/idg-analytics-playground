create or replace view V_ORDERQTYTABLE_ANALYTICS(
	JOBNUMBER,
	COMPONENTNUMBER,
	ESTIMATENUMBER,
	TOTAL_QUANTITY,
	TOTAL_PRODUCTIONMARKUP,
	TOTAL_MATERIALMARKUP,
	TOTAL_STOCKMARKUP,
	TOTAL_MANUALPRICE,
	TOTAL_PRODUCTIONCOST,
	TOTAL_MATERIALCOST,
	TOTAL_STOCKCOST,
	TOTAL_OSCOST,
	TOTAL_TOTALMINUTES,
	TOTAL_TOTALCOST,
	TOTAL_TOTALPRICE,
	TOTAL_PRODUCTIONPRICE,
	TOTAL_MATERIALPRICE,
	TOTAL_STOCKPRICE,
	TOTAL_OSPRICE,
	TOTAL_ADDCOLORCOST,
	TOTAL_ADDCOLORPRICE,
	TOTAL_ADDCOLORMATCOST,
	TOTAL_ADDCOLORMATPRICE,
	TOTAL_GRIDPRICE,
	TOTAL_COMMISSIONAMOUNT,
	TOTAL_ADDMCOST,
	TOTAL_ADDMPRICE,
	TOTAL_TAXAMOUNTA,
	TOTAL_TAXAMOUNTB,
	TOTAL_TAXAMOUNTC,
	TOTAL_TAXAMOUNTD,
	TOTAL_DISCOUNTAMOUNT,
	TOTAL_QUANTITYPERPACKAGE,
	TOTAL_SETPRODUCTIONMARKUP,
	TOTAL_SETMATERIALMARKUP,
	TOTAL_SETPAPERMARKUP,
	TOTAL_SETOSSMARKUP,
	TOTAL_SETPRODUCTIONPRICE,
	TOTAL_SETMATERIALPRICE,
	TOTAL_SETPAPERPRICE,
	TOTAL_SETOSSPRICE,
	TOTAL_SETTOTALPRICE,
	TOTAL_SETPROFITDOLLARS,
	TOTAL_MANUALUNITPRICE,
	TOTAL_AIPRODUCTIONCOST,
	TOTAL_COMBOUNITCOST,
	TOTAL_COMBOUNITPRICE,
	TOTAL_TAXOVERRIDEAMOUNT,
	TOTAL_UNITPRICE,
	TOTAL_ROYALTYAMOUNT,
	QUANTITY_LINE_COUNT
) as
SELECT
    JOBNUMBER,
    COMPONENTNUMBER,
    ESTIMATENUMBER,

    SUM(QUANTITY) AS TOTAL_QUANTITY,
    SUM(PRODUCTIONMARKUP) AS TOTAL_PRODUCTIONMARKUP,
    SUM(MATERIALMARKUP) AS TOTAL_MATERIALMARKUP,
    SUM(STOCKMARKUP) AS TOTAL_STOCKMARKUP,
    SUM(MANUALPRICE) AS TOTAL_MANUALPRICE,

    SUM(PRODUCTIONCOST) AS TOTAL_PRODUCTIONCOST,
    SUM(MATERIALCOST) AS TOTAL_MATERIALCOST,
    SUM(STOCKCOST) AS TOTAL_STOCKCOST,
    SUM(OSCOST) AS TOTAL_OSCOST,

    SUM(TOTALMINUTES) AS TOTAL_TOTALMINUTES,
    SUM(TOTALCOST) AS TOTAL_TOTALCOST,
    SUM(TOTALPRICE) AS TOTAL_TOTALPRICE,

    SUM(PRODUCTIONPRICE) AS TOTAL_PRODUCTIONPRICE,
    SUM(MATERIALPRICE) AS TOTAL_MATERIALPRICE,
    SUM(STOCKPRICE) AS TOTAL_STOCKPRICE,
    SUM(OSPRICE) AS TOTAL_OSPRICE,

    SUM(ADDCOLORCOST) AS TOTAL_ADDCOLORCOST,
    SUM(ADDCOLORPRICE) AS TOTAL_ADDCOLORPRICE,
    SUM(ADDCOLORMATCOST) AS TOTAL_ADDCOLORMATCOST,
    SUM(ADDCOLORMATPRICE) AS TOTAL_ADDCOLORMATPRICE,

    SUM(GRIDPRICE) AS TOTAL_GRIDPRICE,
    SUM(COMMISSIONAMOUNT) AS TOTAL_COMMISSIONAMOUNT,

    SUM(ADDMCOST) AS TOTAL_ADDMCOST,
    SUM(ADDMPRICE) AS TOTAL_ADDMPRICE,

    SUM(TAXAMOUNTA) AS TOTAL_TAXAMOUNTA,
    SUM(TAXAMOUNTB) AS TOTAL_TAXAMOUNTB,
    SUM(TAXAMOUNTC) AS TOTAL_TAXAMOUNTC,
    SUM(TAXAMOUNTD) AS TOTAL_TAXAMOUNTD,

    SUM(DISCOUNTAMOUNT) AS TOTAL_DISCOUNTAMOUNT,
    SUM(QUANTITYPERPACKAGE) AS TOTAL_QUANTITYPERPACKAGE,

    SUM(SETPRODUCTIONMARKUP) AS TOTAL_SETPRODUCTIONMARKUP,
    SUM(SETMATERIALMARKUP) AS TOTAL_SETMATERIALMARKUP,
    SUM(SETPAPERMARKUP) AS TOTAL_SETPAPERMARKUP,
    SUM(SETOSSMARKUP) AS TOTAL_SETOSSMARKUP,

    SUM(SETPRODUCTIONPRICE) AS TOTAL_SETPRODUCTIONPRICE,
    SUM(SETMATERIALPRICE) AS TOTAL_SETMATERIALPRICE,
    SUM(SETPAPERPRICE) AS TOTAL_SETPAPERPRICE,
    SUM(SETOSSPRICE) AS TOTAL_SETOSSPRICE,

    SUM(SETTOTALPRICE) AS TOTAL_SETTOTALPRICE,
    SUM(SETPROFITDOLLARS) AS TOTAL_SETPROFITDOLLARS,

    SUM(MANUALUNITPRICE) AS TOTAL_MANUALUNITPRICE,
    SUM(AIPRODUCTIONCOST) AS TOTAL_AIPRODUCTIONCOST,
    SUM(COMBOUNITCOST) AS TOTAL_COMBOUNITCOST,
    SUM(COMBOUNITPRICE) AS TOTAL_COMBOUNITPRICE,
    SUM(TAXOVERRIDEAMOUNT) AS TOTAL_TAXOVERRIDEAMOUNT,
    SUM(UNITPRICE) AS TOTAL_UNITPRICE,
    SUM(ROYALTYAMOUNT) AS TOTAL_ROYALTYAMOUNT,

    COUNT(*) AS QUANTITY_LINE_COUNT

FROM DATA_VALIDATION.RAW_SQL_SERVER.ORDERQTYTABLE
GROUP BY
    JOBNUMBER,
    COMPONENTNUMBER,
    ESTIMATENUMBER;;
